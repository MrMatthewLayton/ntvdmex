#!/usr/bin/env python3
"""gen-vbepm.py -- assemble src/vdd/vbe_pm.asm and write src/vdd/vbe_pm.h (#53).

The VBE 2.0 protected-mode interface block is real 32-bit x86 code that a client copies
and calls; it is kept as assembly SOURCE and turned into a C byte array here, so the
bytes in the host are always the bytes of the file a reader can review. Run after any
edit to vbe_pm.asm:

    python3 tools/gen/gen-vbepm.py
"""
import os, struct, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "src", "vdd", "vbe_pm.asm")
SRC_RM = os.path.join(ROOT, "src", "vdd", "vbe_rm.asm")   # #273: the real-mode WinFuncPtr
OUT = os.path.join(ROOT, "src", "vdd", "vbe_pm.h")

with tempfile.TemporaryDirectory() as td:
    binp = os.path.join(td, "vbe_pm.bin")
    subprocess.check_call(["nasm", "-f", "bin", SRC, "-o", binp])
    blob = open(binp, "rb").read()
    rmp = os.path.join(td, "vbe_rm.bin")
    subprocess.check_call(["nasm", "-f", "bin", SRC_RM, "-o", rmp])
    rm = open(rmp, "rb").read()

win, start, pal, ports = struct.unpack_from("<4H", blob, 0)
def rows(b):
    return "\n".join("    " + ", ".join("0x%02X" % x for x in b[i:i + 12]) + ","
                     for i in range(0, len(b), 12))
lines = [rows(blob)]
hdr = """/* vbe_pm.h -- GENERATED by tools/gen/gen-vbepm.py from src/vdd/vbe_pm.asm. Do not edit by hand.
 *
 * The VBE 2.0 protected-mode interface block handed out by INT 10h AX=4F0Ah (#53):
 * a 4-word table (SetWindow, SetDisplayStart, SetPalette, port list -- each an offset
 * from the start of the block), the I/O port list, and relocatable 32-bit code.
 * Also the real-mode WinFuncPtr stub from src/vdd/vbe_rm.asm (#273).
 */
#ifndef VBE_PM_H
#define VBE_PM_H
#define VBE_PM_LEN       %du
#define VBE_PM_SETWINDOW 0x%04Xu
#define VBE_PM_SETSTART  0x%04Xu
#define VBE_PM_SETPAL    0x%04Xu
#define VBE_PM_PORTS     0x%04Xu
static const unsigned char vbe_pm_block[VBE_PM_LEN] = {
%s
};
/* #273: the real-mode window function (vbe_rm.asm), far-called through WinFuncPtr. */
#define VBE_RM_LEN       %du
static const unsigned char vbe_rm_winfunc[VBE_RM_LEN] = {
%s
};
#endif
""" % (len(blob), win, start, pal, ports, "\n".join(lines), len(rm), rows(rm))
open(OUT, "w").write(hdr)
print("real-mode winfunc: %d bytes" % len(rm))
print("wrote %s: %d bytes, setwindow=%#x setstart=%#x setpal=%#x ports=%#x"
      % (os.path.relpath(OUT, ROOT), len(blob), win, start, pal, ports))
